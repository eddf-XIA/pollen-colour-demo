"""
End-to-end demo: generate synthetic scenes -> save / reload them -> detect dish -> classify pixels ->
CIELAB distributions + metrics of the measured pixels -> CSV tables, label maps, figure.

Every output row carries data_origin = DATA_ORIGIN so synthetic numbers cannot be mistaken for research results.
"""
import json
import os
import sys

import numpy as np
import pandas as pd
from scipy import ndimage as ndi

from . import __version__
from . import dish as DI
from . import distribution as DS
from . import io as IO
from . import segmentation as SG
from . import synthetic as SY
from .params import PARAMS, params_hash

DATA_ORIGIN = 'synthetic_demo'
FLOAT_FORMAT = '%.6g'


def measure(rgb):
    """Dish detection + pixel classification + colour summary for one decoded uint8 sRGB image."""
    dish = DI.detect_dish(rgb)
    seg = SG.classify(rgb, dish)
    meas = seg['cls_crop'] == SG.MEASURED
    lab = seg['lab_crop'][meas]
    y0, _, x0, _ = seg['box']
    ys, xs = np.nonzero(meas)
    srgb = rgb[ys + y0, xs + x0]                    # the decoded values themselves (never resampled)
    return dict(dish=dish, seg=seg, lab=lab, srgb=srgb)


def class_fractions(label):
    in_dish = label > SG.OUTSIDE_DISH
    n = int(in_dish.sum())
    out = {'n_dish_px': n}
    for c, name in SG.CLASS_NAMES.items():
        if c != SG.OUTSIDE_DISH:
            out[f'frac_{name}'] = float((label[in_dish] == c).mean()) if n else float('nan')
    return out


def truth_check(label, dish, truth, shadow_se_radius_px):
    """Segmentation vs the synthetic ground truth (possible only because the scenes are generated)."""
    gt, rho = truth['gt'], truth['rho']
    T = truth['dish']
    meas = label == SG.MEASURED
    out = dict(dish_R_true=T['R'], dish_R_detected=dish['R'], dish_R_rel_error=abs(dish['R'] - T['R']) / T['R'],
               dish_centre_error_px=float(np.hypot(dish['cx'] - T['cx'], dish['cy'] - T['cy'])))
    out['measured_frac_background'] = float(np.isin(gt[meas], [0, 1, 2]).mean())
    out['measured_purity_load'] = float((gt[meas] == 4).mean())
    floor = (gt == 2) & (rho < PARAMS['segmentation']['rim_zone_rho'])
    out['floor_not_measured'] = float((label[floor] != SG.MEASURED).mean()) if floor.any() else float('nan')
    gap = gt == 3
    rs = shadow_se_radius_px
    width = ndi.maximum_filter(2 * ndi.distance_transform_edt(gap), size=2 * rs + 1)
    narrow, wide = gap & (width < 2 * rs + 1), gap & (width >= 2 * rs + 1)
    out['narrow_crevice_not_measured'] = float((label[narrow] != SG.MEASURED).mean())
    out['wide_void_not_measured'] = float((label[wide] != SG.MEASURED).mean())
    loads_meas = meas & (gt == 4)
    for k, name in enumerate(truth['names']):
        m = truth['interior'] & (truth['grain_col'] == k) & (rho < 0.8)
        out[f'retention_{name}'] = float((label[m] == SG.MEASURED).mean())
        # does segmentation change the composition? share of visible load px vs share of measured load px
        out[f'share_true_{name}'] = float((truth['grain_col'][gt == 4] == k).mean())
        out[f'share_measured_{name}'] = float((truth['grain_col'][loads_meas] == k).mean())
    ret = [out[f'retention_{n}'] for n in truth['names']]
    out['retention_spread'] = float(max(ret) - min(ret))
    return out


def library_versions():
    import cv2
    import matplotlib
    import PIL
    import scipy
    import skimage
    return {'python': sys.version.split()[0], 'numpy': np.__version__, 'scipy': scipy.__version__,
            'scikit-image': skimage.__version__, 'opencv': cv2.__version__, 'Pillow': PIL.__version__,
            'pandas': pd.__version__, 'matplotlib': matplotlib.__version__}


OUTPUT_NOTE = """# These outputs are synthetic

Every file in this folder was generated by `python -m pollen_colour_demo` from computer-generated images.
They are not research data, contain no real photographs, and have no biological meaning. The numbers show what
the code computes on synthetic scenes; they are not estimates of accuracy on real photographs.
"""


def run(out_dir, scenes=None, figure=True):
    os.makedirs(out_dir, exist_ok=True)
    for sub in ('inputs', 'label_maps'):
        os.makedirs(os.path.join(out_dir, sub), exist_ok=True)
    metric_rows, hist_rows, truth_rows, panels = [], [], [], []
    specs = scenes or SY.SCENES
    for spec in specs:
        rgb_gen, truth = SY.make_scene(**spec)
        sid = spec['scene_id']
        p = os.path.join(out_dir, 'inputs', f'{sid}.png')
        IO.save_png(rgb_gen, p)
        rgb = IO.load_rgb(p)                       # measure what was written, like a real input
        if not np.array_equal(rgb, rgb_gen):
            raise RuntimeError('PNG round trip is not lossless')
        r = measure(rgb)
        label = r['seg']['label']
        IO.save_png(np.repeat(label[..., None], 3, 2), os.path.join(out_dir, 'label_maps', f'{sid}_labels.png'))
        d = r['dish']
        row = dict(data_origin=DATA_ORIGIN, scene_id=sid, dish_cx=d['cx'], dish_cy=d['cy'], dish_R=d['R'],
                   rim_fit_rms_px=d['rim_fit_rms_px'], rim_rays_used=d['rim_rays_used'])
        row.update(class_fractions(label))
        row.update(DS.colour_metrics(r['lab']))
        metric_rows.append(row)
        counts, edges = DS.lab_histogram(r['lab'])
        for h in DS.histogram_long(counts, edges):
            hist_rows.append(dict(data_origin=DATA_ORIGIN, scene_id=sid, **h))
        for k, v in truth_check(label, d, truth, r['seg']['shadow_se_radius_px']).items():
            truth_rows.append(dict(data_origin=DATA_ORIGIN, scene_id=sid, metric=k, value=v))
        panels.append(dict(scene_id=sid, rgb=rgb, label=label, dish=d, lab=r['lab'], srgb=r['srgb'], mix=spec['mix']))

    tables = {'colour_metrics.csv': pd.DataFrame(metric_rows),
              'colour_distribution_lab_histogram.csv': pd.DataFrame(hist_rows),
              'synthetic_truth_check.csv': pd.DataFrame(truth_rows)}
    for name, df in tables.items():
        df.to_csv(os.path.join(out_dir, name), index=False, float_format=FLOAT_FORMAT, lineterminator='\n')
    info = dict(data_origin=DATA_ORIGIN, package_version=__version__, params_hash=params_hash(), params=PARAMS,
                scenes=[{k: v for k, v in s.items()} for s in specs], libraries=library_versions())
    with open(os.path.join(out_dir, 'run_info.json'), 'w', encoding='utf-8', newline='\n') as fh:
        json.dump(info, fh, indent=2)
    with open(os.path.join(out_dir, 'OUTPUTS_ARE_SYNTHETIC.md'), 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(OUTPUT_NOTE)
    if figure:
        from .figure import make_figure
        make_figure(panels, os.path.join(out_dir, 'demo_figure.png'))
    return tables
